function stripHtml(html) {
  return html
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeName(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

const delay = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchJson(url, retries = 3) {
  for (let attempt = 0; attempt <= retries; attempt++) {
    try {
      const res = await fetch(url);
      if (res.ok) return await res.json();
    } catch {
      // network flake — retry with backoff
    }
    if (attempt < retries) await delay(500 * (attempt + 1));
  }
  return null;
}

/**
 * Page the full English translation list into a normalized-name → base id index.
 * Cached to a temp file so re-runs of this script don't re-page ~3.3k rows.
 */
async function buildNameIndex() {
  const cachePath = path.join(os.tmpdir(), 'wger-name-index.json');
  if (fs.existsSync(cachePath) && !process.argv.includes('--no-cache')) {
    const cached = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
    console.log(`  using cached wger index (${cached.length} names) — pass --no-cache to refresh`);
    return new Map(cached);
  }
  const index = new Map();
  let url = `${WGER}/exercise-translation/?format=json&language=${ENGLISH}&limit=200`;
  let page = 0;
  while (url) {
    const data = await fetchJson(url);
    if (!data) throw new Error(`wger translation index failed at page ${page}`);
    for (const t of data.results) {
      const key = normalizeName(t.name);
      if (!index.has(key)) index.set(key, t.exercise);
    }
    url = data.next;
    page++;
    process.stderr.write(`\r  indexing wger page ${page}…`);
    await delay(120);
  }
  process.stderr.write(`\r  indexed ${index.size} wger names (${page} pages)\n`);
  fs.writeFileSync(cachePath, JSON.stringify([...index]));
  return index;
}

/**
 * Resolve a curated name to a wger base id: exact normalized match first, then
 * the shortest indexed name containing every token of the curated name.
 * `alias` (the optional 6th CATALOG column) overrides the lookup name for the
 * cases where wger's own naming makes token matching pick the wrong movement
 * (e.g. "Barbell Bench Press" → wger's decline bench entry).
 */
function resolveBaseId(name, index, alias) {
  const key = normalizeName(alias ?? name);
  if (index.has(key)) return index.get(key);
  const tokens = key.split(' ');
  let best = null;
  for (const [indexed, id] of index) {
    if (tokens.every((tok) => indexed.includes(tok))) {
      if (!best || indexed.length < best.len) best = { id, len: indexed.length };
    }
  }
  return best?.id ?? null;
}

async function fetchInfo(baseId) {
  return fetchJson(`${WGER}/exerciseinfo/${baseId}/?format=json`);
}

async function main() {
  const outArg = process.argv.indexOf('--out');
  const outPath = path.resolve(
    outArg >= 0 ? process.argv[outArg + 1] : 'scripts/seed-data/exercises.json',
  );

  console.log('Building wger name index…');
  const index = await buildNameIndex();

  const exercises = [];
  const usedBaseIds = new Set();
  let matched = 0;

  for (const [name, primary, secondary, movementType, restSeconds, alias] of CATALOG) {
    const resolved = resolveBaseId(name, index, alias);
    // One wger entry per exercise: a fuzzy match that lands on an already-used
    // base id is a wrong match (it would copy another movement's description).
    const baseId = resolved != null && !usedBaseIds.has(resolved) ? resolved : null;
    if (baseId != null) usedBaseIds.add(baseId);
    let description = null;
    let imageUrl = null;
    const extraMuscles = new Set();

    if (baseId != null) {
      const info = await fetchInfo(baseId);
      if (info) {
        const en = (info.translations ?? []).find((t) => t.language === ENGLISH);
        if (en?.description) description = stripHtml(en.description) || null;
        const img = (info.images ?? []).find((i) => i.is_main) ?? (info.images ?? [])[0];
        if (img?.image) imageUrl = img.image;
        for (const m of [...(info.muscles ?? []), ...(info.muscles_secondary ?? [])]) {
          const label = (m.name_en || m.name || '').toLowerCase();
          const mapped = WGER_MUSCLE_MAP[label];
          if (mapped) extraMuscles.add(mapped);
        }
        // wger entries that claim half the body ("Plank" → biceps, quads, …)
        // are noise; drop the whole set rather than pollute secondary muscles.
        if (extraMuscles.size > MAX_WGER_SECONDARY) extraMuscles.clear();
      }
      matched++;
      await delay(150);
    }

    // wger muscles only ever *augment* the secondary list — the curated primary
    // is authoritative because the generator keys off the exercise name.
    const secondaryMuscles = [...new Set([...secondary, ...extraMuscles])].filter(
      (m) => !primary.includes(m),
    );

    exercises.push({
      name,
      primaryMuscles: primary,
      secondaryMuscles,
      movementType,
      restSeconds,
      description,
      imageUrl,
      wgerId: baseId,
    });
    process.stderr.write(`  ${baseId ? '✓' : '·'} ${name}\n`);
  }

  const payload = {
    attribution: ATTRIBUTION,
    generatedBy: 'scripts/build-seed-exercises.mjs',
    count: exercises.length,
    exercises,
  };

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, JSON.stringify(payload, null, 2) + '\n');
  console.log(`\nWrote ${exercises.length} exercises (${matched} matched in wger) → ${outPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
