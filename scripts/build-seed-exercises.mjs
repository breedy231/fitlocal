/**
 * ONE-TIME generator for scripts/seed-data/exercises.json (GitHub #86).
 *
 * Fetches exercise metadata (description, image, muscles, wger id) from the
 * wger API (https://wger.de/api/v2, CC-BY-SA 4.0) for a curated list of
 * canonical gym movements and writes a static, committed JSON catalog.
 *
 *   node scripts/build-seed-exercises.mjs [--out scripts/seed-data/exercises.json]
 *
 * The seed script (scripts/seed.ts) reads ONLY the committed JSON — it never
 * hits the network — so `npm run seed` is offline-capable and deterministic.
 * Re-run this script only when refreshing the catalog.
 *
 * Why a curated name list instead of a raw wger dump: FitLocal's generator maps
 * an exercise to a muscle group by regex over its NAME
 * (MUSCLE_KEYWORDS in packages/api/src/lib/recovery.ts), and the cardio UI
 * switches on CARDIO_PATTERN (packages/shared/src/cardio.ts). A raw dump of
 * ~3.3k wger names is mostly invisible to both. The curated names below are
 * generic gym movements chosen so every muscle in the generator's vocabulary
 * has ≥6 options across several equipment types.
 *
 * Nothing here comes from scripts/jefit-index.json or exercise-corrections.json
 * — the catalog is clean-room wger-only.
 */

