#!/usr/bin/env python3
"""
Daily fitness briefing — writes a Markdown note into the Obsidian vault from
FitLocal production data, then git-commits + pushes it. Runs locally via launchd
(see ~/Library/LaunchAgents/com.brendan.fitlocal-briefing.plist).

The training recommendation is generated by the Claude API (claude-sonnet-5-5),
with a deterministic rule-based fallback if the API key is missing, the call
fails, or the response is empty/junk — so the briefing is never blank. (This
replaced an Ollama/local-LLM call — qwen3:30b-a3b was never actually installed,
so every briefing since Aug silently used the rule-based fallback until this
switch.) ANTHROPIC_API_KEY is read from the repo's .env the same way
FITLOCAL_API_KEY is.

Fetches FitLocal over HTTPS with `curl` (subprocess) deliberately: the system
Python's urllib has no CA bundle on this Mac and fails TLS verification (certifi
gotcha), whereas curl uses the system trust store.

Part 1 (#78): infers the next PPL day from recent workout notes and calls
/generate-workout to get suggested weights, rendered in Obsidian format.

Part 2 (#78): sends a Web Push to all subscribed devices using pywebpush
(optional — skipped with a log message if not installed or VAPID keys missing).
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time
import urllib.error
import urllib.request
import datetime

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENV_PATH = os.path.join(REPO, ".env")
BASE = "https://fitlocal-app.fly.dev/api"
# Obsidian vault is a git clone of github.com/breedy231/vault (cross-device sync).
# Kept OUTSIDE iCloud (~/vault, not ~/Documents) so git is the only sync mechanism.
VAULT_REPO = "/Users/brendanreed/vault"
VAULT_DIR = os.path.join(VAULT_REPO, "Notion/Notebook/Personal/Fitness")
LB_PER_KG = 2.20462
KG_TO_LBS = LB_PER_KG  # alias — same conversion, both names used below

# Plain urllib POST (no `anthropic` SDK dependency) — the launchd job runs
# under the Homebrew-managed /usr/local/bin/python3, which refuses `pip
# install` for anything outside a venv (PEP 668 externally-managed-environment)
# without --break-system-packages. Raw HTTP avoids touching that interpreter's
# packages at all. See build_prompts.py's note re: curl vs urllib TLS — that
# gotcha is specific to fitlocal-app.fly.dev's cert chain, not api.anthropic.com,
# and api.anthropic.com has verified fine over urllib in testing here.
ANTHROPIC_API_URL = "https://api.anthropic.com/v1/messages"
CLAUDE_MODEL = "claude-sonnet-5-5"
CLAUDE_MAX_TOKENS = 300
CLAUDE_TIMEOUT = 60   # seconds
# Cut data older than this (latest weigh-in) is treated as stale: no cut numbers in the
# note or the LLM prompt.
STALE_WEIGHIN_DAYS = 14
LAYOFF_RIR = "3-4 reps in reserve"   # effort cap while returning from a layoff

# PPL rotation order
PPL_ROTATION = ["push", "pull", "legs"]


def git_sync(repo, filepath, message):
    """Pull latest, stage the note, commit if changed, and push. Best-effort."""
    def run(*args):
        return subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True)
    pull = run("pull", "--rebase", "--autostash")
    if pull.returncode != 0:
        print(f"WARN: git pull failed: {pull.stderr.strip()}", file=sys.stderr)
    run("add", filepath)
    if not run("status", "--porcelain").stdout.strip():
        print("git: no change to commit")
        return
    commit = run("commit", "-m", message)
    if commit.returncode != 0:
        print(f"WARN: git commit failed: {commit.stderr.strip()}", file=sys.stderr)
        return
    push = run("push")
    print("git: pushed" if push.returncode == 0 else f"WARN: git push failed: {push.stderr.strip()}",
          file=sys.stderr if push.returncode != 0 else sys.stdout)


def read_env_value(var_name):
    """Read a single VAR=value line from the repo's .env. Returns None if not found."""
    try:
        with open(ENV_PATH) as f:
            for line in f:
                if line.startswith(var_name + "="):
                    return line.split("=", 1)[1].strip()
    except OSError:
        pass
    return None


def read_key():
    key = read_env_value("FITLOCAL_API_KEY")
    if not key:
        raise SystemExit("FITLOCAL_API_KEY not found in " + ENV_PATH)
    return key


def get(path, key, timeout=25, retries=1):
    """GET {BASE}{path} via curl. Returns parsed JSON, or None on failure.
    Retries once: the Fly machine auto-stops when idle and a cold start (Litestream
    restore + boot) can exceed a short timeout on the first request."""
    r = None
    for attempt in range(retries + 1):
        r = subprocess.run(
            ["curl", "-sS", "-m", str(timeout), "-H", f"Authorization: Bearer {key}", BASE + path],
            capture_output=True, text=True,
        )
        if r.returncode == 0 and r.stdout.strip():
            break
        if attempt < retries:
            print(f"WARN: fetch {path} failed ({r.stderr.strip() or 'empty'}); retrying", file=sys.stderr)
            time.sleep(3)
    if r.returncode != 0 or not r.stdout.strip():
        print(f"WARN: fetch {path} failed: {r.stderr.strip()}", file=sys.stderr)
        return None
    try:
        return json.loads(r.stdout)
    except json.JSONDecodeError:
        print(f"WARN: fetch {path} returned non-JSON", file=sys.stderr)
        return None


def infer_next_ppl_day(workouts_data):
    """
    Scan the `notes` field of recent workouts (newest-first) for push/pull/legs.
    Return the next day in the rotation. Default to 'push' if no match found.
    """
    if not workouts_data:
        return "push"
    # workouts are returned newest-first by default
    last_day = None
    for w in workouts_data:
        notes = (w.get("notes") or "").lower()
        for day in PPL_ROTATION:
            if re.search(rf"\b{day}\b", notes):
                last_day = day
                break
        if last_day:
            break
    if last_day is None:
        return "push"
    idx = PPL_ROTATION.index(last_day)
    return PPL_ROTATION[(idx + 1) % len(PPL_ROTATION)]


def round_to_nearest(value, increment):
    """Round value to the nearest multiple of increment."""
    return round(round(value / increment) * increment, 10)


def format_duration(seconds):
    """Format duration in seconds to a human-readable string."""
    if not seconds:
        return "?"
    m, s = divmod(int(seconds), 60)
    if s == 0:
        return f"{m} min"
    return f"{m}:{s:02d}"


def render_exercise_obsidian(ex):
    """
    Render a GeneratedExercise in Obsidian workout format:
      Exercise Name
      [warmup reps] reps x [warmup weight] lbs    <- if warmup set in payload
      [sets] sets x [reps] reps x [weight] lbs
      [N] reps in reserve                          <- omit for bodyweight/cardio

    The /generate-workout response does NOT include a warmup set object — the
    GeneratedExercise shape has suggestedSets/suggestedReps/suggestedWeightKg.
    A warmup set isn't part of the payload, so we skip that line per spec.
    """
    name = ex.get("name", "Unknown")
    # isCardio comes from the generator, which classifies with the canonical
    # CARDIO_PATTERN in packages/shared/src/cardio.ts — do NOT re-derive it
    # here (CLAUDE.md: single source of truth, never redefine).
    is_cardio = ex.get("isCardio", False)
    lines = [name]

    if is_cardio:
        duration_sec = ex.get("suggestedDurationSec")
        lines.append(format_duration(duration_sec))
    else:
        sets = ex.get("suggestedSets", 3)
        reps = ex.get("suggestedReps", 10)
        weight_kg = ex.get("suggestedWeightKg", 0)
        weight_lbs = weight_kg * KG_TO_LBS
        # Round to nearest 2.5 lbs
        weight_lbs_rounded = round_to_nearest(weight_lbs, 2.5)

        if weight_kg > 0:
            # 165 not 165.0, but keep 167.5
            weight_str = f"{weight_lbs_rounded:g}"
            lines.append(f"{sets} sets x {reps} reps x {weight_str} lbs")
        else:
            # Bodyweight — no weight shown
            lines.append(f"{sets} sets x {reps} reps")

        rep_range = ex.get("repRange")
        # Only show RIR for weighted non-cardio exercises
        if weight_kg > 0 and rep_range:
            # The generator sets layoffDays when it lowered the weight for a
            # return from 21+ days off: leave more in the tank on those lifts.
            if ex.get("layoffDays"):
                lines.append(f"{LAYOFF_RIR} (first sessions back)")
            else:
                lines.append("1-2 reps in reserve")

    return "\n".join(lines)


def build_session_section(generate_data, next_day):
    """Build the 'Today's session' Markdown block from /generate-workout response."""
    if not generate_data:
        return None
    exercises = generate_data.get("exercises", [])
    if not exercises:
        return None

    day_label = next_day.capitalize()
    blocks = [f"## Today's Session — {day_label} Day", ""]
    for ex in exercises:
        blocks.append(render_exercise_obsidian(ex))
        blocks.append("")
    return "\n".join(blocks).rstrip()


def rule_based_recommendation(rec, dl, layoff_days=None, injury=None):
    """Deterministic fallback recommendation from recovery + deload flag."""
    if layoff_days:
        weeks = max(1, round(layoff_days / 7))
        guard = (f" Respect the {injury.get('label', 'injury')} restriction and stop any set that brings on symptoms."
                 if injury else "")
        return (f"First session back after about {weeks} weeks: do the planned session at the reduced "
                f"weights, {LAYOFF_RIR}, and add nothing extra.{guard}")
    if not rec:
        return None
    majors = ["chest", "back", "quads", "hamstrings", "shoulders"]
    avg_major = sum(rec.get(m, 0) for m in majors) / len(majors)
    weak = [m for m, v in rec.items() if v < 50]
    if avg_major > 70 and not weak:
        todo = "Lift — next in your PPL rotation. Majors are recovered."
    else:
        todo = "Easy Zone-2 cardio or rest — major muscles aren't fully recovered."
    caveat = (f" Watch your {', '.join(weak)} "
              f"({', '.join(str(rec[m]) + '%' for m in weak)} recovered) — least-recovered tissue."
              if weak else "")
    deload = " A deload is due." if dl and dl.get("suggest") else ""
    return f"{todo}{caveat}{deload}"


def claude_recommendation(rec, dl, tl, cut_line, injury=None, session_summary=None, layoff_days=None):
    """Coaching rec from the Claude API (claude-sonnet-5-5). Returns clean prose, or None
    to trigger the rule-based fallback. Any missing key, API error, or empty/junk
    response falls back — never raises."""
    if not rec:
        return None
    api_key = read_env_value("ANTHROPIC_API_KEY")
    if not api_key:
        print("WARN: ANTHROPIC_API_KEY not found in .env; using fallback", file=sys.stderr)
        return None

    recs = ", ".join(f"{m} {v}%" for m, v in sorted(rec.items(), key=lambda x: x[1]))
    load = f"Training load is {tl.get('ratio')}x baseline ({tl.get('label', '?')})." if tl else ""
    deload = "A deload is flagged as due." if dl and dl.get("suggest") else ""
    injury_line = ""
    if injury:
        injury_line = (
            f"- ACTIVE INJURY RESTRICTION ({injury.get('label', 'injury')}; avoid: "
            f"{', '.join(injury.get('avoidPatterns') or []) or 'see notes'}): "
            f"{injury.get('notes') or ''} Never recommend movements that violate this.\n"
        )
    cut_line_prompt = f"- {cut_line}\n" if cut_line else ""
    # The recovery model only measures time since a muscle was trained. After
    # weeks off it reads 100% everywhere, which is detraining, not readiness.
    layoff_line = ""
    if layoff_days:
        weeks = max(1, round(layoff_days / 7))
        layoff_line = (
            f"- RETURN FROM LAYOFF: he has not trained these lifts for about {weeks} weeks "
            f"({layoff_days} days). The planned weights are already reduced for this. The 100% "
            "recovery numbers reflect time off, NOT readiness. Treat this as a re-entry session: "
            f"conservative effort ({LAYOFF_RIR}), no added sets, weight or extra cardio beyond the "
            "plan, and stop any set that brings on symptoms. Never say to push it.\n"
        )
    cut_goal = ("perform well while on a calorie-deficit cut — don't overreach or dig a recovery hole in the deficit"
                if cut_line else "train consistently without overreaching")
    session_prompt = (
        f"- Today's planned session is already chosen: {session_summary}. Build on it (how hard to "
        "push it, what to add or skip around it, whether to add cardio); do NOT prescribe a "
        "different session or day type.\n" if session_summary else ""
    )
    prompt = (
        "You are Brendan's strength & running coach. Write today's training recommendation.\n\n"
        "His standing goals: (1) build his running — increase distance and consistency, and protect "
        f"impact tissue (calves, shins) so he doesn't get injured; (2) {cut_goal}.\n\n"
        f"Today's data:\n"
        f"- Muscle recovery from a time-since-trained model (higher = longer since trained; it does "
        f"not know about injuries or detraining): {recs}\n"
        f"- {load} {deload}\n"
        f"{cut_line_prompt}"
        f"{layoff_line}"
        f"{injury_line}"
        f"{session_prompt}\n"
        "Recommend what to train today and how hard. Decide which muscle groups are recovered enough "
        "to lift, and whether to run / cross-train on the bike / rest given impact-tissue recovery and "
        "the training load. An active injury restriction or a return from layoff overrides the "
        "goals above: be conservative, and state the effort cap and the injury precaution plainly.\n\n"
        "Respond with ONLY 2-3 sentences (hard maximum 3) of direct recommendation. Do NOT restate the numbers, do NOT "
        "explain your reasoning, do NOT write a preamble. Start with the recommendation itself."
    )
    body = json.dumps({
        "model": CLAUDE_MODEL,
        "max_tokens": CLAUDE_MAX_TOKENS,
        "messages": [{"role": "user", "content": prompt}],
    }).encode("utf-8")
    req = urllib.request.Request(
        ANTHROPIC_API_URL,
        data=body,
        headers={
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=CLAUDE_TIMEOUT) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        print(f"WARN: claude call failed (HTTP {e.code}): {e.read()[:300]}; using fallback", file=sys.stderr)
        return None
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        print(f"WARN: claude call failed ({e}); using fallback", file=sys.stderr)
        return None
    except json.JSONDecodeError:
        print("WARN: claude returned non-JSON; using fallback", file=sys.stderr)
        return None

    text = "".join(
        block.get("text", "") for block in data.get("content", []) if block.get("type") == "text"
    ).strip()
    text = " ".join(text.split())
    # Enforce the 2-3 sentence contract even if the model runs long.
    sentences = re.split(r"(?<=[.!?])\s+", text)
    if len(sentences) > 3:
        text = " ".join(sentences[:3])
    if len(text) < 10:
        print("WARN: claude output too short/empty; using fallback", file=sys.stderr)
        return None
    return text


def send_push_notifications(key, title, body, url="/"):
    """
    Send a Web Push to all subscribed devices. Requires pywebpush + VAPID keys.
    Silently skips if not available. Cleans up expired subscriptions (404/410).
    """
    try:
        from pywebpush import webpush, WebPushException  # type: ignore
    except ImportError:
        print("push skipped: pywebpush not installed", file=sys.stderr)
        return

    vapid_private_key = read_env_value("FITLOCAL_VAPID_PRIVATE_KEY") or os.environ.get("FITLOCAL_VAPID_PRIVATE_KEY")
    vapid_subject = read_env_value("FITLOCAL_VAPID_SUBJECT") or os.environ.get("FITLOCAL_VAPID_SUBJECT")
    if not vapid_private_key or not vapid_subject:
        print("push skipped: FITLOCAL_VAPID_PRIVATE_KEY or FITLOCAL_VAPID_SUBJECT not set", file=sys.stderr)
        return

    subs_data = get("/push-subscriptions", key)
    if not subs_data:
        print("push skipped: no subscriptions or fetch failed", file=sys.stderr)
        return

    payload = json.dumps({"title": title, "body": body, "url": url})
    expired_endpoints = []

    for sub in subs_data:
        endpoint = sub.get("endpoint")
        p256dh = sub.get("keys", {}).get("p256dh")
        auth = sub.get("keys", {}).get("auth")
        if not endpoint or not p256dh or not auth:
            continue
        try:
            webpush(
                subscription_info={
                    "endpoint": endpoint,
                    "keys": {"p256dh": p256dh, "auth": auth},
                },
                data=payload,
                vapid_private_key=vapid_private_key,
                vapid_claims={"sub": vapid_subject},
            )
            print(f"push sent: {endpoint[:60]}...")
        except WebPushException as e:
            status = getattr(e.response, "status_code", None) if hasattr(e, "response") else None
            if status in (404, 410):
                print(f"push: subscription expired ({status}), will remove: {endpoint[:60]}...", file=sys.stderr)
                expired_endpoints.append(endpoint)
            else:
                print(f"WARN: push failed for {endpoint[:60]}...: {e}", file=sys.stderr)
        except Exception as e:
            print(f"WARN: push error for {endpoint[:60]}...: {e}", file=sys.stderr)

    # Clean up expired subscriptions
    for endpoint in expired_endpoints:
        r = subprocess.run(
            [
                "curl", "-sS", "-m", "10",
                "-X", "DELETE",
                "-H", f"Authorization: Bearer {key}",
                "-H", "Content-Type: application/json",
                "-d", json.dumps({"endpoint": endpoint}),
                BASE + "/push-subscriptions",
            ],
            capture_output=True, text=True,
        )
        if r.returncode == 0:
            print(f"push: removed expired subscription {endpoint[:60]}...")
        else:
            print(f"WARN: failed to remove expired subscription: {r.stderr.strip()}", file=sys.stderr)


def main():
    parser = argparse.ArgumentParser(description="FitLocal daily briefing")
    parser.add_argument("--dry-run", action="store_true",
                         help="Print the briefing to stdout instead of writing/committing "
                              "the vault note or sending push notifications.")
    parser.add_argument("--json", action="store_true",
                        help="Print today's rec and session plan as JSON (for the home-ai morning "
                             "Discord briefing) instead of writing the note, committing, or pushing.")
    args = parser.parse_args()

    key = read_key()
    # Warm-up: wake the auto-stopped Fly machine with a long first timeout so the
    # real fetches below don't time out on a cold start.
    get("/health", key, timeout=90, retries=0)
    g = get("/goals", key)
    n = get("/goals/daily-nutrition", key)
    snaps = get("/health-snapshots", key)
    rec_raw = get("/recovery-summary", key)
    dl = get("/deload-check", key)
    tl = get("/training-load", key)
    injury = get("/injury", key)

    # Fetch recent workouts to infer next PPL day
    workouts_data = get("/workouts?limit=10", key)
    next_day = infer_next_ppl_day(workouts_data)

    # Fetch the generated workout plan for today's session
    generate_data = None
    try:
        generate_data = get(f"/generate-workout?dayType={next_day}", key)
    except Exception as e:
        print(f"WARN: generate-workout fetch raised exception: {e}", file=sys.stderr)

    missing = [name for name, v in
               [("goals", g), ("nutrition", n), ("weights", snaps), ("recovery", rec_raw)]
               if v is None]
    rec = {m["name"]: m["recoveryPct"] for m in rec_raw["muscles"]} if rec_raw else {}

    # Latest logged weight + short trend (current-year rows with a body weight).
    ws = []
    if snaps:
        ws = [s for s in snaps
              if str(s.get("date", "")).startswith(str(datetime.date.today().year))
              and s.get("bodyWeightKg")]
        ws.sort(key=lambda s: s["date"])

    # Compute cut figures up front so the recommendation can reference them.
    # Stale data (old weigh-in or cut end date passed) is reported as facts only and kept
    # out of the LLM prompt, so the rec doesn't reason from an old weight.
    cut_block = None
    cut_line = None          # None = omit from the LLM prompt
    weighin_line = "**Weigh-in:** no body-weight log found."
    if ws and not (g and g.get("targetWeightKg")):
        # No cut set (goals cleared): no cut block, just when the last weigh-in was.
        weighin_line = f"**Weigh-in:** latest log is {ws[-1]['date']}."
    elif ws and g:
        last = ws[-1]
        kg = last["bodyWeightKg"]
        lb = kg * LB_PER_KG
        tgt_lb = g["targetWeightKg"] * LB_PER_KG
        togo = lb - tgt_lb
        today_d = datetime.date.today()
        try:
            age_days = (today_d - datetime.date.fromisoformat(str(last["date"])[:10])).days
        except ValueError:
            age_days = None
        end_str = g.get("cutEndDate")
        try:
            cut_over = bool(end_str) and datetime.date.fromisoformat(str(end_str)[:10]) < today_d
        except ValueError:
            cut_over = False
        stale = age_days is None or age_days > STALE_WEIGHIN_DAYS or cut_over
        if stale:
            bits = [f"last weigh-in {last['date']}" + (f" ({age_days} days ago)" if age_days is not None else "")]
            if cut_over:
                bits.append(f"cut target date {end_str} has passed")
            cut_block = f"**Cut:** {'; '.join(bits)}. Cut progress not shown (stale)."
            weighin_line = "**Weigh-in:** weigh in this morning."
        else:
            trend = " → ".join(f'{s["bodyWeightKg"] * LB_PER_KG:.1f}' for s in ws[-5:])
            cut_block = (f"**Cut:** {lb:.1f} lb ({kg:.2f} kg), **{togo:.1f} lb to go** to target "
                         f"{tgt_lb:.1f} lb. Cut ends {end_str or '?'}. "
                         f"Recent 5: {trend} lb (single-day swings are water, not fat).")
            cut_line = f"Cut: {lb:.1f} lb, {togo:.1f} lb to target {tgt_lb:.0f} lb, cut ends {end_str or '?'}."
            weighin_line = f"**Weigh-in:** latest log is {last['date']} — weigh in this morning if you haven't yet."

    session_summary = None
    if generate_data and generate_data.get("exercises"):
        names = ", ".join(e.get("name", "?") for e in generate_data["exercises"][:8])
        session_summary = f"{next_day.capitalize()} day ({names})"

    # Recommendation: Claude Sonnet 5 first, deterministic fallback if it fails/errors.
    # Longest layoff among today's planned lifts (the generator reports it per exercise).
    layoff_days = max((e.get("layoffDays") or 0 for e in (generate_data or {}).get("exercises", [])), default=0) or None

    claude_rec = claude_recommendation(rec, dl, tl, cut_line, injury, session_summary, layoff_days)
    rec_text = claude_rec or rule_based_recommendation(rec, dl, layoff_days, injury)
    rec_source = "Claude Sonnet 5" if claude_rec else "rule-based fallback"

    today = datetime.date.today()
    fname = f"Daily Briefing {today.month}-{today.day}-{str(today.year)[2:]}.md"
    lines = [f"# Daily Briefing — {today.strftime('%A, %B %-d, %Y')}", ""]
    if rec_text:
        lines += [f"**Today:** {rec_text}", ""]
    if cut_block:
        lines += [cut_block, ""]

    # Nutrition.
    if g:
        intake = ""
        if n:
            cur = n.get("calories", {}).get("current")
            prot = n.get("protein", {}).get("current")
            intake = (f" Yesterday's logged intake (Apple Health not synced today yet): {cur} cal / {prot}g protein."
                      if n.get("isStale") else f" Today so far: {cur} cal / {prot}g protein.")
        # Goals are nullable: with no cut set there is no calorie target, only maintenance.
        tgt, prot_t, maint = g.get("targetCalories"), g.get("targetProteinG"), g.get("maintenanceCalories")
        prot_s = f" / {prot_t:.0f}g protein" if prot_t else ""
        if tgt:
            maint_s = f" (maintenance {maint})" if maint else ""
            lines += [f"**Nutrition:** target **{tgt} cal{prot_s}**{maint_s}.{intake}", ""]
        elif maint or prot_t:
            cal_s = f"maintenance **{maint} cal**" if maint else "no calorie target"
            lines += [f"**Nutrition:** {cal_s}{prot_s}, no cut set.{intake}", ""]

    lines += [weighin_line, ""]

    # Today's session plan.
    session_section = build_session_section(generate_data, next_day)
    if session_section:
        lines += [session_section, ""]
    else:
        lines += [f"**Session plan:** {next_day.capitalize()} day — plan unavailable (generate-workout call failed).", ""]

    if missing:
        lines += [f"> ⚠️ Some data was unavailable: {', '.join(missing)}.", ""]
    lines += [f"*Auto-generated from FitLocal prod. Recommendation: {rec_source}.*"]

    if args.json:
        # Consumed by ~/Projects/home-ai/scripts/morning-briefing.js at 07:00. Same rec as the
        # note (one prompt, one fallback); only the output shape differs.
        session = [{"name": ex.get("name", "?"), "plan": render_exercise_obsidian(ex).split("\n")[1:]}
                   for ex in (generate_data or {}).get("exercises", [])]
        print(json.dumps({
            "day": next_day,
            "rec": rec_text,
            "recSource": rec_source,
            "session": session,
            "layoffDays": layoff_days,
            "injury": (injury or {}).get("label") if injury else None,
            "missing": missing + ([] if generate_data else ["session plan"]),
        }))
        return

    if args.dry_run:
        print("--- DRY RUN: not writing vault note, not committing, not sending push ---")
        print("\n".join(lines))
        print(f"--- [rec: {rec_source}]" + (f" (missing: {', '.join(missing)})" if missing else "") + " ---")
        return

    os.makedirs(VAULT_DIR, exist_ok=True)
    path = os.path.join(VAULT_DIR, fname)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{datetime.datetime.now().isoformat(timespec='seconds')} wrote {path} [rec: {rec_source}]"
          + (f" (missing: {', '.join(missing)})" if missing else ""))
    git_sync(VAULT_REPO, path, f"Daily briefing {today.month}-{today.day}-{str(today.year)[2:]}")

    # Part 2: Web Push — send after the note is committed so a push failure never blocks the note.
    # First line only, truncated: iOS clips notification bodies around ~150 chars.
    push_body = (rec_text or f"{next_day.capitalize()} day — check the briefing note.").strip().splitlines()[0][:160]
    push_title = f"Daily Briefing — {next_day.capitalize()} Day"
    send_push_notifications(key, push_title, push_body, url="/")


if __name__ == "__main__":
    main()
